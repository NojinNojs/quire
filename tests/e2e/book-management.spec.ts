import { expect, test } from "./fixtures";

test("account book metadata and deletion persist", async ({ signedInPage: page }) => {
  await page.getByRole("tab", { name: "Enter manually" }).click();
  await page.getByLabel("Title (required)").fill("Account CRUD title");
  await page.getByLabel("Author", { exact: true }).fill("Original author");
  await page.getByRole("button", { name: "Save book" }).click();
  await expect(page.getByText(/Account CRUD title added/)).toBeVisible();
  await page.goto("/#/shelf");
  await page.getByText("Account CRUD title", { exact: true }).click();
  await page.getByRole("button", { name: "Edit book" }).click();
  await page.getByLabel("Title (required)").fill("Account revised title");
  await page.getByLabel("Author", { exact: true }).fill("Revised author");
  await page.getByLabel("Publisher", { exact: true }).fill("Test publisher");
  await page.getByRole("button", { name: "Save book" }).click();
  await expect(page.getByRole("heading", { name: "Account revised title" })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Revised author", { exact: true })).toBeVisible();
  await expect(page.getByText("Test publisher", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Edit book" }).click();
  await page.getByLabel("Title (required)").fill("Discarded title");
  await page.getByRole("button", { name: "Cancel edit" }).click();
  await expect(page.getByRole("heading", { name: "Account revised title" })).toBeVisible();
  await page.getByRole("combobox", { name: "Reading status", exact: true }).selectOption("reading");
  await page.getByRole("link", { name: "Continue reading", exact: true }).click();
  await expect(page).toHaveURL(/#\/today$/);
  await expect(page.getByRole("heading", { name: "Account revised title" })).toBeVisible();
  await page.goto("/#/shelf");
  await page.getByText("Account revised title", { exact: true }).click();
  await page.getByRole("button", { name: "Delete book" }).click();
  await page.getByRole("button", { name: "Cancel delete" }).click();
  await expect(page.getByRole("heading", { name: "Account revised title" })).toBeVisible();
  await page.getByRole("button", { name: "Delete book" }).click();
  await page.getByRole("button", { name: "Confirm delete" }).click();
  await expect(page).toHaveURL(/#\/shelf$/);
  await page.reload();
  await expect(page.getByText("Account revised title", { exact: true })).toHaveCount(0);
});

test("demo edits survive reload and deleting active book clears Today", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("quire:tour:v1:demo", "dismissed"));
  await page.goto("/?demo=1#/search");
  await page.getByRole("tab", { name: "Enter manually" }).click();
  await page.getByLabel("Title (required)").fill("Demo CRUD title");
  await page.getByRole("button", { name: "Save book" }).click();
  await expect(page.getByText("Demo CRUD title added to your shelf.")).toBeVisible();
  await page.goto("/?demo=1#/shelf");
  await page.getByText("Demo CRUD title", { exact: true }).click();
  await page.getByRole("button", { name: "Edit book" }).click();
  await page.getByLabel("Title (required)").fill("Demo revised title");
  await page.getByRole("button", { name: "Save book" }).click();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Demo revised title" })).toBeVisible();
  const detailUrl = page.url();
  await page.goto("/?demo=1#/book/demo-bumi");
  await page.getByRole("button", { name: "Mark as finished" }).click();
  await page.goto(detailUrl);
  await page.getByRole("combobox", { name: "Reading status", exact: true }).selectOption("reading");
  await expect(page.getByRole("link", { name: "Continue reading", exact: true })).toBeVisible();
  await page.goto("/?demo=1#/shelf");
  await page.getByText("Demo revised title", { exact: true }).click();
  await page.getByRole("button", { name: "Delete book" }).click();
  await page.getByRole("button", { name: "Confirm delete" }).click();
  await page.reload();
  await expect(page.getByText("Demo revised title", { exact: true })).toHaveCount(0);
  await page.goto("/?demo=1#/today");
  await expect(page.getByText("Demo revised title", { exact: true })).toHaveCount(0);
});
